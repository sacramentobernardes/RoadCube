// Biblioteca de algoritmos do RoadCube.
// Todos os algoritmos estão na notação WCA, considerando o amarelo em cima
// e o verde na frente (exceto os da cruz/primeira camada, com branco embaixo).
// Rode `npm run verify:algs` após editar para validar cada algoritmo.

export type AlgSet = "beginner" | "f2l" | "oll" | "pll";

export type CubeView = "full" | "cross" | "f2l" | "oll" | "pll" | "ll";

/**
 * O que o algoritmo precisa manter intacto para ser válido (usado na verificação):
 * - "f2l": primeiras duas camadas inteiras (algoritmos de última camada);
 * - "d-layer": camada de baixo inteira (segunda camada do método básico);
 * - "d-layer-but-dfr": camada de baixo exceto a quina frente-direita;
 * - "cross-but-XX": cruz + todos os slots exceto o slot XX (F2L).
 */
export type PreserveRule =
  | "f2l"
  | "d-layer"
  | "d-layer-but-dfr"
  | "cross-but-fr"
  | "cross-but-br"
  | "cross-but-bl";

export interface AlgCase {
  id: string;
  set: AlgSet;
  group: string;
  name: string;
  /** Dica curta de reconhecimento. */
  recognition: string;
  /** O primeiro é o padrão; os demais são alternativas (fingertricks diferentes). */
  algs: string[];
  view: CubeView;
  preserve: PreserveRule;
}

