const CASE_INDEX = new Map(ALG_CASES.map((c) => [c.id, c]));

export function getCase(id: string): AlgCase {
  const found = CASE_INDEX.get(id);
  if (!found) throw new Error(`Caso de algoritmo desconhecido: ${id}`);
  return found;
}

export function casesBySet(set: AlgSet): AlgCase[] {
  return ALG_CASES.filter((c) => c.set === set);
}
